import { useEffect, useState } from "react";
import { useReport } from "../hooks/useReport";
import Loading from "../../../components/ui/loading";
import DetailView from "../../../components/widgets/detail-view";
import StatusBadge from "../../../components/ui/status-badge";
import { formatDate } from "../../../utils/formatDate";
import { formatBytes } from "../utils/formatBytes";
import type { Report } from "../types/report";
import type { BadgeColor } from "../../../types/badgeColor";

interface ReportViewProps {
    id: number;
    isOpen: boolean;
}

const statusColors: Record<string, { text: string; color: string }> = {
    PENDING: { text: "Pending", color: "gray" },
    PROCESSING: { text: "Processing", color: "blue" },
    COMPLETED: { text: "Completed", color: "purple" },
    FAILED: { text: "Failed", color: "red" },
};

const ReportView = ({ id, isOpen }: ReportViewProps) => {
    const { handleView } = useReport();
    const [data, setData] = useState<Report | null>(null);
    const [loading, setLoading] = useState(false);

    useEffect(() => {
        const fetch = async () => {
            if (!isOpen || !id) return;

            try {
                setLoading(true);
                const result = await handleView(id);
                setData(result);
            } catch (err) {
                console.error("Failed to fetch report:", err);
            } finally {
                setLoading(false);
            }
        };

        fetch();
    }, [id, isOpen]);

    if (loading) {
        return (
            <div className="flex items-center justify-center py-20">
                <Loading text="Loading report..." />
            </div>
        );
    }

    if (!data) {
        return <div className="text-center py-10 text-gray-500">No data available</div>;
    }

    const s = statusColors[data.status] || { text: data.status, color: "gray" };

    const files = data.file_type
        ? data.file_type.split(",").map((f) => f.trim()).filter(Boolean)
        : [];

    const fields = [
        { label: "Project", value: data.project?.name || "-" },
        { label: "Type", value: data.type },
        { label: "Format", value: data.format },
        {
            label: "Reporting Period",
            value: data.reporting_period_from && data.reporting_period_to
                ? `${formatDate(data.reporting_period_from, false)} — ${formatDate(data.reporting_period_to, false)}`
                : "-",
        },
        { label: "Status", value: <StatusBadge text={s.text} color={s.color as BadgeColor} /> },
        {
            label: "Files Included",
            value: files.length > 0 ? (
                <div className="flex flex-wrap gap-1.5 justify-end">
                    {files.map((f, i) => (
                        <span key={i} className="text-xs font-medium px-2 py-0.5 bg-primary/10 text-primary rounded-full">
                            {f}
                        </span>
                    ))}
                </div>
            ) : "-",
        },
        { label: "Total Size", value: data.file_size ? formatBytes(data.file_size) : "-" },
        { label: "Generated By", value: data.generatedBy?.user?.name || "-" },
        { label: "Generated At", value: data.generated_at ? formatDate(data.generated_at, true) : "-" },
        { label: "Created At", value: formatDate(data.created_at, true) },
    ];

    return (
        <DetailView
            title={`Report #${data.uid}`}
            subtitle={data.project?.name}
            fields={fields}
        />
    );
};

export default ReportView;