import { useEffect, useState } from "react";
import { Button } from "../../components/ui/button";
import ActionIcon from "../../components/ui/action-icon";
import { FilterToggleButton } from "../../components/widgets/filter-button";
import { ActionButton } from "../../components/widgets/action-button";
import { SelectInput } from "../../components/ui/select-input";
import StatusBadge from "../../components/ui/status-badge";
import EmptyState from "../../components/ui/empty";
import Loading from "../../components/ui/loading";
import Modal from "../../components/ui/modal";
import Popup from "../../components/widgets/popup";
import type { TableColumn } from "../../components/widgets/table";
import Table from "../../components/widgets/table";
import { useReportStore } from "../../features/reports/store/reportStore";
import { useReport } from "../../features/reports/hooks/useReport";
import { useProjectStore } from "../../features/project/store/projectStore";
import GenerateReportForm from "../../features/reports/components/generate-report-form";
import ReportView from "../../features/reports/components/report-view";
import { formatDate } from "../../utils/formatDate";
import { formatBytes } from "../../features/reports/utils/formatBytes";
import type { Report } from "../../features/reports/types/report";
import type { BadgeColor } from "../../types/badgeColor";
import ConnectionError from "../../features/common/network/connectionError";
import { formatCode } from "../../utils/formatCode";

const statusColors: Record<string, { text: string; color: string }> = {
    PENDING: { text: "Pending", color: "gray" },
    PROCESSING: { text: "Processing", color: "blue" },
    COMPLETED: { text: "Completed", color: "purple" },
    FAILED: { text: "Failed", color: "red" },
};

const typeOptions = [
    { label: "All Types", value: "" },
    { label: "Data Package", value: "DATA_PACKAGE" },
    { label: "Beneficiaries", value: "BENEFICIARIES" },
    { label: "Assistance", value: "ASSISTANCE" },
    { label: "Analytics", value: "ANALYTICS" },
    { label: "Project Documentation", value: "PROJECT_DOCUMENTATION" },
];

const statusOptions = [
    { label: "All Status", value: "" },
    { label: "Pending", value: "PENDING" },
    { label: "Processing", value: "PROCESSING" },
    { label: "Completed", value: "COMPLETED" },
    { label: "Failed", value: "FAILED" },
];

const Report = () => {
    const { data, pagination, loading, error, getData } = useReportStore();
    const { data: projects, getData: getProjects } = useProjectStore();

    const {
        filterMode, toggleFilter,
        filters, handleTypeChange, handleStatusChange, handleProjectChange,
        refreshCurrentPage,
        handleDelete, handleDownload, downloadingId,
    } = useReport();

    const [generateModalOpen, setGenerateModalOpen] = useState(false);
    const [viewModalOpen, setViewModalOpen] = useState(false);
    const [deletePopup, setDeletePopup] = useState(false);
    const [selectedReport, setSelectedReport] = useState<Report | null>(null);

    useEffect(() => {
        getProjects();
    }, [getProjects]);

    const reportColumns: TableColumn[] = [
        { key: "id", label: "ID", visibleOn: "lg", render: (_, globalIndex) => formatCode("RPT", globalIndex) },
        {
            key: "report",
            label: "Report",
            visibleOn: "always",
            render: (row: Report) => (
                <div>
                    <p className="font-semibold text-gray-900">{row.project?.name || "-"}</p>
                    <p className="text-xs text-gray-400 mt-0.5">{row.type} · {row.format}</p>
                </div>
            ),
        },
        {
            key: "period",
            label: "Period",
            visibleOn: "md",
            render: (row: Report) =>
                row.reporting_period_from && row.reporting_period_to
                    ? `${formatDate(row.reporting_period_from, false, false)} — ${formatDate(row.reporting_period_to, false, false)}`
                    : "-",
        },
        {
            key: "status",
            label: "Status",
            visibleOn: "always",
            render: (row: Report) => {
                const s = statusColors[row.status] || { text: row.status, color: "gray" };
                return <StatusBadge text={s.text} color={s.color as BadgeColor} />;
            },
        },
        {
            key: "generated_by",
            label: "Generated By",
            visibleOn: "lg",
            render: (row: Report) => row.generatedBy?.user?.name || "-",
        },
        // {
        //     key: "file_size",
        //     label: "Size",
        //     visibleOn: "sm",
        //     render: (row: Report) => (row.file_size ? formatBytes(row.file_size) : "-"),
        // },
        {
            key: "action",
            label: "Action",
            visibleOn: "always",
            render: (row: Report) => (
                <div className="flex items-center space-x-3">
                    <ActionIcon
                        name="view"
                        onClick={() => {
                            setSelectedReport(row);
                            setViewModalOpen(true);
                        }}
                    />
                    {row.status === "COMPLETED" && (
                        <ActionIcon
                            name={downloadingId === row.id ? "spinner" : "download"}
                            onClick={() => handleDownload(row)}
                        />
                    )}
                    <ActionIcon
                        name="trash"
                        onClick={() => {
                            setSelectedReport(row);
                            setDeletePopup(true);
                        }}
                    />
                </div>
            ),
        },
    ];

    return (
        <div className="grid grid-cols-1 gap-4 mt-2">
            <div className="flex flex-col items-start justify-start rounded-sm bg-white gap-4">
                <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4 w-full">
                    <div className="flex flex-row gap-4 w-full sm:w-auto">
                        <FilterToggleButton isOpen={filterMode} onToggle={toggleFilter} />
                    </div>
                    <div className="flex flex-row gap-3 w-full sm:w-auto">
                        <ActionButton className="h-10 w-[14%] sm:w-auto" onClick={() => refreshCurrentPage(pagination?.page || 1)} />
                        <Button className="w-full sm:w-auto" onClick={() => setGenerateModalOpen(true)}>
                            Generate Report
                        </Button>
                    </div>
                </div>

                {filterMode && (
                    <div className="flex flex-col sm:flex-row gap-4 p-4 bg-gray-50 rounded-lg w-full">
                        <div className="w-full sm:w-50">
                            <SelectInput options={typeOptions} value={filters.type} onChange={(e) => handleTypeChange(e.target.value)} />
                        </div>
                        <div className="w-full sm:w-50">
                            <SelectInput options={statusOptions} value={filters.status} onChange={(e) => handleStatusChange(e.target.value)} />
                        </div>
                        <div className="w-full sm:w-50">
                            <SelectInput
                                options={[
                                    { label: "All Projects", value: "" },
                                    ...projects.map((p: any) => ({ label: p.name, value: String(p.id) })),
                                ]}
                                value={filters.project_id}
                                onChange={(e) => handleProjectChange(e.target.value)}
                            />
                        </div>
                    </div>
                )}

                {loading && data.length === 0 ? (
                    <div className="flex justify-center w-full mt-20">
                        <Loading text="Please wait..." />
                    </div>
                ) : !data.length && error ? (
                    <ConnectionError
                        title={error.type === "no_network" ? undefined : "Something Went Wrong"}
                        message={error.type === "no_network" ? undefined : (error.message || "An unexpected error occurred.")}
                        onRetry={() => getData(pagination?.page || 1)}
                    />
                ) : data.length === 0 ? (
                    <div className="w-full bg-gray-50 rounded-md">
                        <EmptyState title="No Reports Found" />
                    </div>
                ) : (
                    <>
                        <Table columns={reportColumns} data={data} className="" />

                        <div className="flex flex-col sm:flex-row justify-between w-full gap-4 mt-1">
                            <div>
                                <p className="text-gray-500">
                                    Total Records: <span className="font-bold text-black">{pagination?.total || 0}</span>
                                </p>
                            </div>

                            <div>
                                <nav aria-label="Page navigation">
                                    <ul className="inline-flex -space-x-px text-sm">
                                        <li>
                                            <button
                                                disabled={!pagination?.hasPrev}
                                                onClick={() => refreshCurrentPage(pagination!.page - 1)}
                                                className={`flex items-center justify-center px-3 h-8 leading-tight border border-gray-300 rounded-s-lg ${
                                                    !pagination?.hasPrev
                                                        ? "text-gray-400 bg-gray-100 cursor-not-allowed"
                                                        : "text-gray-500 bg-white hover:bg-gray-100 hover:text-gray-700"
                                                }`}
                                            >
                                                Previous
                                            </button>
                                        </li>

                                        {(() => {
                                            const total = pagination?.totalPages || 1;
                                            const current = pagination?.page || 1;
                                            const pages: (number | string)[] = [];

                                            pages.push(1);
                                            if (current > 3) pages.push("...");
                                            for (let i = Math.max(2, current - 1); i <= Math.min(total - 1, current + 1); i++) {
                                                if (!pages.includes(i)) pages.push(i);
                                            }
                                            if (current < total - 2) pages.push("...");
                                            if (total > 1) pages.push(total);

                                            return pages.map((page, index) =>
                                                page === "..." ? (
                                                    <li key={`ellipsis-${index}`}>
                                                        <span className="flex items-center justify-center px-3 h-8 border border-gray-300 text-gray-500">...</span>
                                                    </li>
                                                ) : (
                                                    <li key={page}>
                                                        <button
                                                            onClick={() => refreshCurrentPage(page as number)}
                                                            className={`flex items-center justify-center px-3 h-8 border border-gray-300 ${
                                                                page === current
                                                                    ? "text-primary bg-primary/10 font-medium"
                                                                    : "text-gray-500 bg-white hover:bg-gray-100 hover:text-gray-700"
                                                            }`}
                                                        >
                                                            {page}
                                                        </button>
                                                    </li>
                                                )
                                            );
                                        })()}

                                        <li>
                                            <button
                                                disabled={!pagination?.hasNext}
                                                onClick={() => refreshCurrentPage(pagination!.page + 1)}
                                                className={`flex items-center justify-center px-3 h-8 leading-tight border border-gray-300 rounded-e-lg ${
                                                    !pagination?.hasNext
                                                        ? "text-gray-400 bg-gray-100 cursor-not-allowed"
                                                        : "text-gray-500 bg-white hover:bg-gray-100 hover:text-gray-700"
                                                }`}
                                            >
                                                Next
                                            </button>
                                        </li>
                                    </ul>
                                </nav>
                            </div>
                        </div>
                    </>
                )}
            </div>

            <Modal
                isOpen={generateModalOpen}
                onClose={() => setGenerateModalOpen(false)}
                title="Generate Report"
                children={
                    <GenerateReportForm
                        isOpen={generateModalOpen}
                        onSuccess={() => {
                            setGenerateModalOpen(false);
                            getData(1);
                        }}
                    />
                }
            />

            <Modal
                isOpen={viewModalOpen}
                onClose={() => setViewModalOpen(false)}
                title="View Report"
                children={
                    selectedReport && <ReportView id={selectedReport.id} isOpen={viewModalOpen} />
                }
            />

            <Popup
                loading={loading}
                open={deletePopup}
                onClose={() => setDeletePopup(false)}
                title="Delete Report"
                description={
                    selectedReport ? (
                        <>
                            You are about to <strong>delete</strong> the report for{" "}
                            <span className="font-bold">{selectedReport.project?.name}</span> ({selectedReport.type}).
                            Do you want to proceed?
                        </>
                    ) : "Loading..."
                }
                confirmText="Delete"
                cancelText="Cancel"
                onConfirm={async () => {
                    if (!selectedReport) return;
                    const success = await handleDelete(selectedReport.id, pagination?.page || 1);
                    if (success) {
                        setDeletePopup(false);
                        setSelectedReport(null);
                    }
                }}
                confirmButtonClass="bg-red-500 hover:bg-red-400"
            />
        </div>
    );
};

export default Report;